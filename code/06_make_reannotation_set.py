#!/usr/bin/env python3
"""Prepare a manual re-annotation set for the cases whose slice index the reviewer moved.

Moving the target slice invalidates the body-composition GT, which was drawn on the old
slice. For each moved case this extracts the CT at the new index, runs that case's
out-of-fold body-composition model over it, and writes the prediction as a Slicer-ready
.seg.nrrd for the annotator to retouch. The previous slice and its GT travel along for
comparison. The model that produced the draft never saw this case during training.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import SimpleITK as sitk
from matplotlib.colors import ListedColormap

PREDICT_BIN = "/opt/conda/envs/nnunetv2/bin/nnUNetv2_predict"
NNUNET_RESULTS = os.environ.get("PRIOR_NNUNET_RESULTS", "")  # set only for the reannotation step
BRANCH_DATASET = {"inferior": "Dataset817_InferiorSMA300PreservedFolds",
                  "middle": "Dataset818_MiddleSMA300PreservedFolds"}
TRAINER, PLANS, CONFIG, CHECKPOINT = "nnUNetTrainer_500epochs", "nnUNetPlans", "2d", "checkpoint_best.pth"
LABEL_NAMES = {1: "muscle", 2: "sfat", 3: "vfat", 4: "mfat"}
OVERLAY = ListedColormap([(0, 0, 0, 0), (0.2, 0.8, 1.0, 1), (0.4, 1.0, 0.4, 1),
                          (1.0, 0.65, 0.0, 1), (1.0, 0.0, 0.0, 1)])


def extract_slice(ct_path: Path, z: int, out_path: Path) -> sitk.Image:
    volume = sitk.ReadImage(str(ct_path))
    if z < 0 or z >= volume.GetSize()[2]:
        raise ValueError(f"{ct_path}: z={z} outside 0..{volume.GetSize()[2] - 1}")
    sl = volume[:, :, z:z + 1]
    sitk.WriteImage(sl, str(out_path), True)
    return sl


def write_seg_nrrd(prediction: Path, out_path: Path) -> None:
    """Match the existing GT layout: one binary labelmap carrying segments 1..4."""
    image = sitk.ReadImage(str(prediction))
    image = sitk.Cast(image, sitk.sitkUInt8)
    for index, label in enumerate(sorted(LABEL_NAMES)):
        image.SetMetaData(f"Segment{index}_LabelValue", str(label))
        image.SetMetaData(f"Segment{index}_Name", f"Label {label}")
        image.SetMetaData(f"Segment{index}_NameAutoGenerated", "0")
    image.SetMetaData("Segmentation_ContainedRepresentationNames", "Binary labelmap|")
    sitk.WriteImage(image, str(out_path), True)


def preview(ct_slice: Path, seg: Path, previous_ct: Path, previous_seg: Path, out_path: Path,
            title: str) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(11, 5.6))
    for ax, (ct_path, seg_path, caption) in zip(axes, [
        (previous_ct, previous_seg, "previous slice + existing GT"),
        (ct_slice, seg, "new slice + model draft"),
    ]):
        ct_image = sitk.ReadImage(str(ct_path))
        ct = np.clip((sitk.GetArrayFromImage(ct_image)[0] + 150) / 400.0, 0, 1)
        ax.imshow(ct, cmap="gray")
        if seg_path.exists():
            # the stored GT is cropped, so put it back on the CT grid before overlaying
            seg_image = sitk.Resample(sitk.ReadImage(str(seg_path)), ct_image, sitk.Transform(),
                                      sitk.sitkNearestNeighbor, 0, sitk.sitkUInt8)
            mask = sitk.GetArrayFromImage(seg_image)[0].astype(float)
            ax.imshow(np.ma.masked_where(mask == 0, mask), cmap=OVERLAY, alpha=0.35,
                      vmin=0, vmax=4, interpolation="nearest")
        ax.set_title(caption, fontsize=10)
        ax.set_xticks([])
        ax.set_yticks([])
    fig.suptitle(title, fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=100)
    plt.close(fig)


def rewrite_manifest(out_root: Path, root: Path) -> int:
    """Rebuild the manifest from every info.json on disk.

    A run restricted with --cases must not drop the cases it did not touch, so the manifest is
    derived from what is actually staged rather than from this run alone. Rows keep the original
    order: branch, then fold, then the case order of the branch label table.
    """
    order = {}
    for rank, branch in enumerate(BRANCH_DATASET):
        for index, row in enumerate(csv.DictReader((root / "labels" / f"{branch}_labels.csv").open())):
            order[(branch, row["case_id"])] = (rank, index)

    records = [json.loads(path.read_text()) for path in out_root.glob("*/*/info.json")]
    records.sort(key=lambda r: (order[(r["branch"], r["case_id"])][0], r["fold"],
                                order[(r["branch"], r["case_id"])][1]))

    fields = [k for k in records[0] if k != "labels"]
    with (out_root / "reannotation_manifest.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for record in records:
            writer.writerow({k: v for k, v in record.items() if k != "labels"})
    return len(records)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(Path(__file__).resolve().parents[1] / "config.json"))
    ap.add_argument("--branches", nargs="+", default=["inferior", "middle"])
    ap.add_argument("--cases", nargs="+", default=None,
                    help="only regenerate these case ids; cases already on disk stay in the manifest")
    ap.add_argument("--device", default="cuda")
    args = ap.parse_args()

    cfg = json.loads(Path(args.config).read_text())
    root = Path(cfg["project_root"])
    dataset_dir = root / "dataset"
    out_root = root / "reannotation"
    manifest = []

    for branch in args.branches:
        selected = set(args.cases) if args.cases else None
        rows = [r for r in csv.DictReader((root / "labels" / f"{branch}_labels.csv").open())
                if r["z_index"] != r["z_index_original"]
                and (selected is None or r["case_id"] in selected)]
        if not rows:
            print(f"[{branch}] no moved cases")
            continue
        branch_root = out_root / branch
        branch_root.mkdir(parents=True, exist_ok=True)
        print(f"[{branch}] {len(rows)} moved cases", flush=True)

        by_fold: dict[int, list[dict]] = {}
        with tempfile.TemporaryDirectory() as tmp:
            staging = Path(tmp)
            for row in rows:
                fold = int(row["fold"])
                fold_input = staging / f"fold_{fold}" / "input"
                fold_input.mkdir(parents=True, exist_ok=True)
                extract_slice(dataset_dir / row["case_id"] / "ct.nii.gz", int(row["z_index"]),
                              fold_input / f"{row['case_id']}_0000.nii.gz")
                by_fold.setdefault(fold, []).append(row)

            for fold, fold_rows in sorted(by_fold.items()):
                fold_input = staging / f"fold_{fold}" / "input"
                fold_output = staging / f"fold_{fold}" / "pred"
                fold_output.mkdir(parents=True, exist_ok=True)
                command = [PREDICT_BIN, "-i", str(fold_input), "-o", str(fold_output),
                           "-d", BRANCH_DATASET[branch], "-c", CONFIG, "-f", str(fold),
                           "-tr", TRAINER, "-p", PLANS, "-chk", CHECKPOINT, "-device", args.device]
                print(f"[{branch} fold {fold}] predicting {len(fold_rows)} cases", flush=True)
                subprocess.run(command, check=True, env={
                    **os.environ,
                    "nnUNet_results": NNUNET_RESULTS,
                    "nnUNet_raw": str(staging / "raw"),
                    "nnUNet_preprocessed": str(staging / "prep"),
                    "MPLCONFIGDIR": str(staging / "mpl"),
                })

                for row in fold_rows:
                    case_id = row["case_id"]
                    case_out = branch_root / case_id
                    (case_out / "previous").mkdir(parents=True, exist_ok=True)
                    shutil.copy2(fold_input / f"{case_id}_0000.nii.gz", case_out / f"{case_id}.nii.gz")
                    write_seg_nrrd(fold_output / f"{case_id}.nii.gz", case_out / f"{case_id}_mask.seg.nrrd")
                    shutil.copy2(dataset_dir / case_id / "reference" / f"{branch}_ct.nii.gz",
                                 case_out / "previous" / f"{case_id}.nii.gz")
                    shutil.copy2(dataset_dir / case_id / "gt" / f"{branch}_mask.seg.nrrd",
                                 case_out / "previous" / f"{case_id}_mask.seg.nrrd")

                    info = {"case_id": case_id, "branch": branch, "fold": fold,
                            "z_index_new": int(row["z_index"]),
                            "z_index_previous": int(row["z_index_original"]),
                            "delta": int(row["z_index"]) - int(row["z_index_original"]),
                            "spacing_z_mm": float(row["spacing_z_mm"]),
                            "draft_model": f"{BRANCH_DATASET[branch]} fold {fold} (out-of-fold for this case)",
                            "labels": LABEL_NAMES}
                    (case_out / "info.json").write_text(json.dumps(info, indent=2) + "\n")
                    preview(case_out / f"{case_id}.nii.gz", case_out / f"{case_id}_mask.seg.nrrd",
                            case_out / "previous" / f"{case_id}.nii.gz",
                            case_out / "previous" / f"{case_id}_mask.seg.nrrd",
                            case_out / "preview.png",
                            f"{case_id}  fold {fold}  {branch}  z {row['z_index_original']} -> {row['z_index']}")
                    manifest.append(info)
                    print(f"   [{branch}] {case_id} z {row['z_index_original']} -> {row['z_index']}", flush=True)

    if manifest:
        total = rewrite_manifest(out_root, root)
        print(f"[DONE] {out_root}  regenerated={len(manifest)}  manifest cases={total}")
    else:
        print(f"[DONE] {out_root}  nothing to regenerate")


if __name__ == "__main__":
    main()
